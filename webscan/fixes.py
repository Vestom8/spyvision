def steps_for(kind: str, recommendation: str = "") -> List[str]:
    """Список шагов исправления (для Finding.fix_steps)."""
    return list(fix_guide(kind, recommendation)["steps"])


def fix_guide(kind: str, recommendation: str = "") -> FixGuide:
    """Полная инструкция: введение, шаги, проверка."""
    guide = FIX_GUIDES.get(kind or "")
    if guide:
        return {
            "intro": guide["intro"],
            "steps": list(guide["steps"]),
            "verify": list(guide.get("verify") or []),
        }

    steps = _steps_from_text(recommendation)
    intro = (recommendation or "").strip()
    if len(steps) >= 2 and intro:
        # Не дублируем длинный текст: короткое введение + шаги
        first = intro.split(".")[0].strip()
        intro = (first + ".") if first else "Выполните шаги ниже."
    elif not intro:
        intro = "Выполните шаги ниже, чтобы устранить находку."

    verify = [
        "Повторите проверку сканером или вручную воспроизведите исходный признак — "
        "он должен исчезнуть.",
        "Убедитесь, что исправление применено на всех окружениях (production и staging).",
    ]
    return {"intro": intro, "steps": steps, "verify": verify}


